def init_database(app):
    """Initializes tables and seeds initial products if database is unpopulated."""
    with app.app_context():
        db.create_all()

        # Check if products already exist
        existing_count = Product.query.count()
        if existing_count == 0:
            seed_items = get_initial_seed_products()
            for item in seed_items:
                product = Product(
                    id=item["id"],
                    name=item["name"],
                    brand=item.get("brand"),
                    model=item.get("model"),
                    category=item["category"],
                    description=item.get("description"),
                    image_url=item.get("image_url"),
                    product_url=item["product_url"],
                    source_website=item["source_website"],
                    current_price=item["current_price"],
                    original_price=item.get("original_price"),
                    discount_percentage=item.get("discount_percentage"),
                    rating=item.get("rating", 4.0),
                    review_count=item.get("review_count", 100),
                    availability=item.get("availability", "In Stock"),
                    data_type=item.get("data_type", "sample"),
                )
                product.specifications = item.get("specifications", {})
                db.session.add(product)

                # Add historical price points
                for hist_price, hist_date in item.get("history", []):
                    history_entry = PriceHistory(
                        product_id=item["id"],
                        price=hist_price,
                        website=item["source_website"],
                        retrieval_timestamp=hist_date,
                        data_source="Catalog Seed",
                        data_type="sample",
                    )
                    db.session.add(history_entry)

            db.session.commit()
